import { test, expect } from 'bun:test';
import { assertReadQuery as a } from '../src/main/mcatzp/readquery';
const ok = (e: any, q: string) => expect(() => a(e, q)).not.toThrow();
const no = (e: any, q: string) => expect(() => a(e, q)).toThrow();
test('reads pass', () => {
  ok('postgresql', 'SELECT * FROM users WHERE id = 1');
  ok('postgresql', "WITH a AS (SELECT 1) SELECT * FROM a");
  ok('mysql', 'SHOW CREATE TABLE users; DESCRIBE users');
  ok('postgresql', 'EXPLAIN SELECT 1');
  ok('sqlite', 'PRAGMA table_info(users)');
  ok('redis', 'GET a\nHGETALL b');
  ok('mongodb', 'db.users.find({})');
  ok('mongodb', 'db.users.aggregate([{$match:{}}])');
  ok('elasticsearch', 'GET /i/_search\n{"query":{"match_all":{}}}');
  ok('postgresql', "SELECT 'DROP TABLE x' AS note, created_at, updated_at FROM t");
});
test('writes refused', () => {
  no('postgresql', 'DELETE FROM users');
  no('postgresql', 'SELECT 1; DROP TABLE x');
  no('postgresql', 'WITH d AS (DELETE FROM t RETURNING *) SELECT * FROM d');
  no('postgresql', 'WITH a AS (SELECT 1 # 2), d AS (DELETE FROM t RETURNING 1) SELECT * FROM d');
  no('postgresql', "SELECT set_config('default_transaction_read_only','off',false)");
  no('postgresql', "SELECT 1 # 2, set_config('x','y',false)");
  no('postgresql', "SELECT 'a\\', set_config('x','y',false) --'");
  no('postgresql', 'EXPLAIN ANALYZE DELETE FROM t');
  no('postgresql', 'EXPLAIN (ANALYZE) WITH d AS (DELETE FROM t RETURNING 1) SELECT * FROM d');
  no('postgresql', "SELECT nextval('s')");
  no('postgresql', "SET default_transaction_read_only = off");
  no('postgresql', 'BEGIN');
  no('mysql', "SELECT 1 /*! INTO OUTFILE '/tmp/x' */");
  no('mysql', "SELECT * FROM t INTO OUTFILE '/tmp/x'");
  no('mysql', 'SELECT SLEEP(100)');
  no('sqlite', 'PRAGMA user_version = 3');
  no('sqlite', 'PRAGMA journal_mode(wal)');
  no('sqlite', "ATTACH DATABASE '/tmp/x' AS y");
  no('redis', 'FLUSHALL');
  no('redis', 'SET a b');
  no('redis', 'GET a\nDEL b');
  no('redis', 'CLIENT PAUSE 1000');
  no('mongodb', 'db.users.deleteMany({})');
  no('mongodb', 'db.users.aggregate([{$out:"x"}])');
  no('mongodb', 'db.users.find({$where:"1"})');
  no('elasticsearch', 'DELETE /i');
  no('elasticsearch', 'POST /i/_update_by_query\n{}');
  no('postgresql', '   ');
});
